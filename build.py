#!/usr/bin/env python3
"""Build the résumé from resume.yaml.

Outputs:
  index.html             public web page (GitHub Pages); private contact items omitted
  <pdf_filename>         public PDF linked from the web page; private items omitted
  out/<pdf_filename>     private PDF with every contact item; git-ignored, for sending

Usage:
  python3 build.py            # HTML + both PDFs
  python3 build.py --no-pdf   # HTML only

PDFs are printed with headless Chrome/Chromium/Brave/Edge. Set $CHROME to pick a binary.
"""
import argparse
import html
import os
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
CONTENT = ROOT / "resume.yaml"
PRIVATE_DIR = ROOT / "out"

BROWSER_CANDIDATES = [
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    "/Applications/Chromium.app/Contents/MacOS/Chromium",
    "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser",
    "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
    "google-chrome", "google-chrome-stable", "chromium", "chromium-browser", "microsoft-edge",
]


def e(text):
    return html.escape(str(text), quote=True)


def render_contact(items, include_private):
    rows = []
    for item in items:
        if item.get("private") and not include_private:
            continue
        text = e(item["text"])
        if item.get("url"):
            text = f'<a href="{e(item["url"])}">{text}</a>'
        rows.append(f"<li>{text}</li>")
    return "\n".join(rows)


def render_skills(skills):
    return "\n".join(
        f'<dt>{e(s["category"])}</dt><dd>{e(", ".join(s["items"]))}</dd>' for s in skills
    )


def render_project(p):
    meta = " · ".join(e(x) for x in (p.get("stack"), p.get("dates")) if x)
    bullets = "\n".join(f"<li>{e(b)}</li>" for b in p["bullets"])
    return f"""<article class="r-role">
<div class="r-role-head"><h3 class="r-role-name">{e(p["name"])}</h3><span class="r-role-meta">{meta}</span></div>
<ul class="r-bullets">
{bullets}
</ul>
</article>"""


def render_job(job):
    titles = "\n".join(
        f'<div class="r-title">{e(t["title"])}<span class="r-title-dates">{e(t["dates"])}</span></div>'
        for t in job.get("titles", [])
    )
    meta = " · ".join(e(x) for x in (job.get("location"), job.get("dates")) if x)
    projects = "\n".join(render_project(p) for p in job.get("projects", []))
    return f"""<div class="r-company"><h3 class="r-company-name">{e(job["company"])}</h3><span class="r-meta">{meta}</span></div>
<div class="r-titles">
{titles}
</div>
{projects}"""


def render_education(items):
    return "\n".join(
        f"""<div class="r-edu">
<div><span class="r-degree">{e(ed["degree"])}</span> <span class="r-school">— {e(ed["institution"])}</span></div>
<span class="r-meta">{e(ed["dates"])}</span>
</div>"""
        for ed in items
    )


def render(data, *, include_private, web, base_href=None):
    name, headline = data["name"], data["headline"]
    title = f"{name} — {headline}"
    description = data.get("meta", {}).get("description", "")
    pdf = data["pdf_filename"]
    base = f'<base href="{e(base_href)}">\n' if base_href else ""
    bar = (
        f"""<div class="r-bar">
<div class="r-bar-label">Résumé &nbsp;·&nbsp; {e(name)}</div>
<a class="r-dl" href="{e(pdf)}" download>Download PDF</a>
</div>
"""
        if web
        else ""
    )
    experience = "\n".join(render_job(j) for j in data["experience"])
    return f"""<!DOCTYPE html>
<!-- Generated by build.py from resume.yaml — edit those, not this file. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
{base}<title>{e(title)}</title>
<meta name="description" content="{e(description)}">
<meta name="author" content="{e(name)}">
<meta property="og:type" content="profile">
<meta property="og:title" content="{e(title)}">
<meta property="og:description" content="{e(description)}">
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'%3E%3Crect width='100' height='100' fill='%23ec3013'/%3E%3Ctext x='50' y='64' font-family='Helvetica,Arial,sans-serif' font-size='40' font-weight='700' fill='%23fff' text-anchor='middle'%3EAS%3C/text%3E%3C/svg%3E">
<link rel="preload" href="assets/fonts/archivo-latin.woff2" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="assets/resume.css">
</head>
<body>
{bar}<main class="r-page">
<header class="r-head">
<div>
<h1 class="r-name">{e(name)}</h1>
<div class="r-headline">{e(headline)}</div>
</div>
<ul class="r-contact">
{render_contact(data["contact"], include_private)}
</ul>
</header>

<section class="r-sec">
<h2 class="r-h">Summary</h2>
<p class="r-summary">{e(data["summary"])}</p>
</section>

<section class="r-sec">
<h2 class="r-h">Technical Skills</h2>
<dl class="r-skills">
{render_skills(data["skills"])}
</dl>
</section>

<section class="r-sec">
<h2 class="r-h">Experience</h2>
{experience}
</section>

<section class="r-sec">
<h2 class="r-h">Education</h2>
{render_education(data["education"])}
</section>
</main>
</body>
</html>
"""


def find_browser():
    if os.environ.get("CHROME"):
        return os.environ["CHROME"]
    for candidate in BROWSER_CANDIDATES:
        path = candidate if os.path.isabs(candidate) else shutil.which(candidate)
        if path and os.path.exists(path):
            return path
    sys.exit("No Chrome/Chromium found for PDF export. Set $CHROME or run with --no-pdf.")


def pdf_complete(path):
    try:
        with open(path, "rb") as f:
            f.seek(-32, os.SEEK_END)
            return b"%%EOF" in f.read()
    except OSError:
        return False


def print_pdf(browser, page_html, out_path, timeout=90):
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.unlink(missing_ok=True)
    # A throwaway profile keeps headless Chrome from touching a running browser session.
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "resume.html"
        src.write_text(page_html, encoding="utf-8")
        proc = subprocess.Popen(
            [
                browser, "--headless", "--disable-gpu", "--no-first-run",
                "--no-default-browser-check", f"--user-data-dir={tmp}/profile",
                "--no-pdf-header-footer", "--allow-file-access-from-files",
                f"--print-to-pdf={out_path}", src.as_uri(),
            ],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )
        # Headless Chrome on macOS often writes the PDF and then never exits,
        # so wait for a finished file rather than for the process.
        deadline = time.monotonic() + timeout
        while proc.poll() is None and not pdf_complete(out_path):
            if time.monotonic() > deadline:
                proc.kill()
                sys.exit(f"Timed out printing {out_path.name}")
            time.sleep(0.25)
        if proc.poll() is None:
            proc.terminate()
            try:
                proc.wait(timeout=10)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.wait()
    if not pdf_complete(out_path):
        sys.exit(f"Browser exited without writing {out_path.name}")
    print(f"wrote {out_path.relative_to(ROOT)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--no-pdf", action="store_true", help="skip PDF export")
    args = parser.parse_args()

    data = yaml.safe_load(CONTENT.read_text(encoding="utf-8"))

    (ROOT / "index.html").write_text(render(data, include_private=False, web=True), encoding="utf-8")
    print("wrote index.html")

    if args.no_pdf:
        return
    browser = find_browser()
    base = ROOT.as_uri() + "/"
    pdf = data["pdf_filename"]
    print_pdf(browser, render(data, include_private=False, web=False, base_href=base), ROOT / pdf)
    print_pdf(browser, render(data, include_private=True, web=False, base_href=base), PRIVATE_DIR / pdf)


if __name__ == "__main__":
    main()
